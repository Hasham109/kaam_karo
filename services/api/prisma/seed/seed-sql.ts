/**
 * Builds the idempotent seed script (T2.6, owner A03) from the pure data files.
 * - SCOPE-CAT-001/002, CAT-SVC-001…012: 22 BP §63 families (category) + 351 items (service),
 *   all with the interim quote-only defaults (service-defaults.data.ts, OQ-085).
 * - SCOPE-GEO-001/002, OPS-ADMIN-023: cities + whole-city zone (cities.data.ts; D-007, D-019).
 * - CFG-RULE-001, D-024: per-city family activation rows; only launch families active, only in
 *   Lahore. No service-level activation row is seeded (a service follows its family).
 * - CFG-RULE-001…012: GLOBAL config_rule versions from config.seed.ts, and the key policy rows
 *   from the registry (SEC-REVIEW-T2.6 #2) when A01's config_key_policy table exists.
 * - SEC-BASE-010 (SEC-REVIEW-T2.6 #7): every config row and activation row the seed inserts gets
 *   one audit row (actor role SYSTEM, source_metadata.actor = SYSTEM_SEED, reason = its citation).
 * Re-running never overwrites: every INSERT skips rows that already exist (ON CONFLICT /
 * NOT EXISTS), so admin changes made after the first seed stay (BP §64 "without a release").
 * config_rule is append-only (BP §26): a seed row is written only when the key has no GLOBAL row.
 */
import { CONFIG_KEYS } from '../../src/modules/config/config-keys.ts';
import { buildPolicySql } from '../tools/config-policy.ts';
import { CATALOG_FAMILIES, serviceCode } from './catalog.data.ts';
import { CITIES } from './cities.data.ts';
import { CONFIG_SEEDS, type ConfigSeed } from './config.seed.ts';
import { DEV_TEST_LIMITS } from './dev-test-limits.seed.ts';
import { SERVICE_DEFAULTS } from './service-defaults.data.ts';

/** SQL string literal (standard_conforming_strings = on, the PostgreSQL default). */
export function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlBool(value: boolean): string {
  return value ? 'true' : 'false';
}

function sqlNullableText(value: string | null): string {
  return value === null ? 'NULL' : sqlString(value);
}

function sqlJson(value: unknown): string {
  return value === null ? 'NULL' : sqlString(JSON.stringify(value));
}

/** source_metadata of every seed audit row (SEC-REVIEW-T2.6 #7). */
export const SEED_AUDIT_SOURCE = { actor: 'SYSTEM_SEED', client: 'seed', task: 'T2.6' } as const;
const SEED_SOURCE_SQL = `${sqlString(JSON.stringify(SEED_AUDIT_SOURCE))}::jsonb`;

export interface SeedSummary {
  readonly families: number;
  readonly services: number;
  readonly cities: number;
  readonly configKeys: number;
}

export function seedSummary(): SeedSummary {
  return {
    families: CATALOG_FAMILIES.length,
    services: CATALOG_FAMILIES.reduce((n, f) => n + f.services.length, 0),
    cities: CITIES.length,
    configKeys: CONFIG_SEEDS.length,
  };
}

/**
 * config_key_policy rows (SEC-REVIEW-T2.6 #2): generated from the registry by A01's
 * prisma/tools/config-policy.ts (one generator, one source). Written before any config row,
 * because the config_rule guard trigger refuses keys without a policy row.
 */
export function buildKeyPolicySql(): string {
  return buildPolicySql(CONFIG_KEYS);
}

/** GLOBAL config rows + one SYSTEM audit row per inserted row. */
function configInsertSql(
  rows: readonly ConfigSeed[],
  condition: 'NO_GLOBAL_ROW' | 'LATEST_GLOBAL_NULL',
  effectiveFrom: string,
  action: string,
): string {
  const values = rows
    .map((c) => `  (${sqlString(c.key)}, ${sqlJson(c.value)}, ${sqlString(c.source)})`)
    .join(',\n');
  const where =
    condition === 'NO_GLOBAL_ROW'
      ? `NOT EXISTS (SELECT 1 FROM "config_rule" r WHERE r."key" = v.key AND r."scope" = 'GLOBAL')`
      : `(SELECT r."value" FROM "config_rule" r WHERE r."key" = v.key AND r."scope" = 'GLOBAL' ` +
        `ORDER BY r."effective_from" DESC LIMIT 1) IS NULL`;
  return (
    `WITH v(key, value, source) AS (VALUES\n${values}\n),\n` +
    `ins AS (\n  INSERT INTO "config_rule" ("key", "scope", "scope_ref_id", "value", "effective_from")\n` +
    `  SELECT v.key, 'GLOBAL'::"config_scope", NULL, v.value::jsonb, ${effectiveFrom} FROM v WHERE ${where}\n` +
    `  RETURNING "id", "key", "value", "effective_from"\n)\n` +
    `INSERT INTO "audit_log" ("actor_user_id", "actor_role", "actor_sub_roles", "action", "object_type", "object_id", "before", "after", "reason", "source_metadata")\n` +
    `SELECT NULL, 'SYSTEM'::"actor_role", '{}', ${sqlString(action)}, 'config_rule', ins."id"::text, NULL, ` +
    `jsonb_build_object('key', ins."key", 'scope', 'GLOBAL', 'value', ins."value", 'effectiveFrom', ins."effective_from"), ` +
    `'seed T2.6: ' || v.source, ${SEED_SOURCE_SQL}\nFROM ins JOIN v ON v.key = ins."key";`
  );
}

export function buildSeedSql(): string {
  const out: string[] = [];
  out.push('-- GENERATED by prisma/seed/seed-sql.ts (T2.6, A03). Do not edit by hand.');
  out.push('BEGIN;');

  // ---- Cities and zones (SCOPE-GEO-001/002) ------------------------------------------------
  for (const city of CITIES) {
    out.push(
      `INSERT INTO "city" ("code", "name_en", "name_ur", "is_listed", "is_active") VALUES (` +
        `${sqlString(city.code)}, ${sqlString(city.en)}, ${sqlString(city.ur)}, ` +
        `${sqlBool(city.isListed)}, ${sqlBool(city.isActive)}) ON CONFLICT ("code") DO NOTHING;`,
    );
    // SEC-REVIEW-T2.6 #8: zones are keyed on their stable code (unique per city, A01 migration
    // 20261024000000), and a zone is created only while the city has none, so a renamed or
    // deactivated zone is never re-created (also on databases seeded before the code existed).
    for (const zone of city.zones) {
      out.push(
        `INSERT INTO "service_zone" ("city_id", "code", "name_en", "name_ur", "area", "is_active") ` +
          `SELECT c."id", ${sqlString(zone.code)}, ${sqlString(zone.en)}, ${sqlString(zone.ur)}, NULL, ${sqlBool(zone.isActive)} ` +
          `FROM "city" c WHERE c."code" = ${sqlString(city.code)} AND NOT EXISTS (` +
          `SELECT 1 FROM "service_zone" z WHERE z."city_id" = c."id") ` +
          `ON CONFLICT ("city_id", "code") DO NOTHING;`,
      );
    }
  }

  // ---- Families (SCOPE-CAT-001) -----------------------------------------------------------
  out.push(
    `INSERT INTO "category" ("code", "name_en", "name_ur") VALUES\n` +
      CATALOG_FAMILIES.map(
        (f) => `  (${sqlString(f.code)}, ${sqlString(f.en)}, ${sqlString(f.ur)})`,
      ).join(',\n') +
      `\nON CONFLICT ("code") DO NOTHING;`,
  );

  // ---- Services (SCOPE-CAT-001, CAT-SVC-001…011) ------------------------------------------
  const d = SERVICE_DEFAULTS;
  const rows = CATALOG_FAMILIES.flatMap((f) =>
    f.services.map(
      (s) =>
        `  (${sqlString(f.code)}, ${sqlString(serviceCode(f.code, s.en))}, ${sqlString(s.en)}, ${sqlString(s.ur)})`,
    ),
  );
  const sellingModes = d.sellingModes.map(sqlString).join(', ');
  out.push(
    `INSERT INTO "service" ("category_id", "code", "name_en", "name_ur", "price_model", "selling_modes", ` +
      `"inspection_expected", "quote_required", "emergency_allowed", "required_verification_level", ` +
      `"pricing_unit", "estimated_duration_minutes", "materials_policy")\n` +
      `SELECT cat."id", v.code, v.name_en, v.name_ur, ${sqlString(d.priceModel)}::"price_model", ` +
      `ARRAY[${sellingModes}]::"selling_mode"[], ${sqlBool(d.inspectionExpected)}, ${sqlBool(d.quoteRequired)}, ` +
      `${sqlBool(d.emergencyAllowed)}, ${sqlNullableText(d.requiredVerificationLevel)}::"verification_level", ` +
      `${sqlNullableText(d.pricingUnit)}, NULL, ${sqlNullableText(d.materialsPolicy)}::"materials_policy"\n` +
      `FROM (VALUES\n${rows.join(',\n')}\n) AS v(family, code, name_en, name_ur)\n` +
      `JOIN "category" cat ON cat."code" = v.family\n` +
      `ON CONFLICT ("code") DO NOTHING;`,
  );

  // ---- Per-city family activation (CFG-RULE-001; D-024) + audit (SEC-REVIEW-T2.6 #7) ---------
  for (const city of CITIES) {
    const values = CATALOG_FAMILIES.map(
      (f) =>
        `  (${sqlString(f.code)}, ${sqlBool(city.activeFamilies === 'LAUNCH_FAMILIES' && f.launchFamily)})`,
    );
    out.push(
      `WITH ins AS (\n  INSERT INTO "catalog_activation" ("city_id", "category_id", "is_active")\n` +
        `  SELECT c."id", cat."id", v.is_active FROM (VALUES\n${values.join(',\n')}\n) AS v(family, is_active)\n` +
        `  JOIN "category" cat ON cat."code" = v.family\n` +
        `  JOIN "city" c ON c."code" = ${sqlString(city.code)}\n` +
        `  ON CONFLICT ("city_id", "category_id") WHERE "category_id" IS NOT NULL DO NOTHING\n` +
        `  RETURNING "id", "city_id", "category_id", "is_active"\n)\n` +
        `INSERT INTO "audit_log" ("actor_user_id", "actor_role", "actor_sub_roles", "action", "object_type", "object_id", "before", "after", "reason", "source_metadata")\n` +
        `SELECT NULL, 'SYSTEM'::"actor_role", '{}', 'FAMILY_ACTIVATION_SEEDED', 'catalog_activation', ins."id"::text, NULL, ` +
        `jsonb_build_object('cityId', ins."city_id", 'categoryId', ins."category_id", 'isActive', ins."is_active"), ` +
        `CASE WHEN ins."is_active" THEN 'seed T2.6: D-024 day-one family (D-007 Lahore)' ELSE 'seed T2.6: D-024 inactive family' END, ` +
        `${SEED_SOURCE_SQL}\nFROM ins;`,
    );
  }

  // ---- Key policy (SEC-REVIEW-T2.6 #2) before any config row ---------------------------------
  out.push(buildKeyPolicySql());

  // ---- GLOBAL config (CFG-RULE-001…012) + audit ----------------------------------------------
  out.push(
    configInsertSql(CONFIG_SEEDS, 'NO_GLOBAL_ROW', 'CURRENT_TIMESTAMP', 'CONFIG_RULE_SEEDED'),
  );

  out.push('COMMIT;');
  return `${out.join('\n')}\n`;
}

/**
 * DEV/TEST ONLY: explicit test values for fail-closed keys whose latest GLOBAL value is null
 * (SEC-REVIEW-T2.6 #1). A new append-only version, effective a moment after the null seed row
 * (clock_timestamp), audited as SYSTEM_SEED. run.ts refuses this outside development/test.
 */
export function buildDevTestLimitsSql(): string {
  return (
    `-- GENERATED by prisma/seed/seed-sql.ts (T2.6, A03): DEV/TEST LIMITS ONLY.\nBEGIN;\n` +
    `${configInsertSql(DEV_TEST_LIMITS, 'LATEST_GLOBAL_NULL', 'clock_timestamp()', 'CONFIG_RULE_DEV_TEST_SEEDED')}\n` +
    `COMMIT;\n`
  );
}
