/**
 * Schema/migration helper (T2.3; DATA-001). Run from services/api with Node 24:
 *
 *   node prisma/tools/db-schema.ts init       Build the first migration from the schema:
 *                                            PostGIS + Prisma DDL + CHECKs + append-only + COMMENT ON.
 *   node prisma/tools/db-schema.ts comments   Print the COMMENT ON statements that the existing
 *                                            migrations do not have yet (paste into a new migration
 *                                            created with `prisma migrate dev --create-only`).
 *
 * The DDL comes from `prisma migrate diff --from-empty --to-schema` (no database needed).
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildCommentStatements, parseCommentStatements, renderCommentSql } from './comments.ts';
import { readSchemaDir } from './schema-model.ts';

export const API_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const SCHEMA_DIR = join(API_ROOT, 'prisma', 'schema');
export const MIGRATIONS_DIR = join(API_ROOT, 'prisma', 'migrations');
export const SQL_DIR = join(API_ROOT, 'prisma', 'sql');
export const INIT_MIGRATION = '20261023000000_init';
/** Hand-written SQL appended after the Prisma DDL, in this order. */
export const SQL_AFTER_DDL = [
  '10_constraints.sql',
  '20_privileges.sql',
  '30_integrity.sql',
] as const;

/** Concatenated COMMENT ON state of all migrations, in migration order. */
export function commentsInMigrations(dir = MIGRATIONS_DIR): Map<string, string> {
  const state = new Map<string, string>();
  if (!existsSync(dir)) return state;
  for (const name of readdirSync(dir).sort()) {
    const file = join(dir, name, 'migration.sql');
    if (existsSync(file)) parseCommentStatements(readFileSync(file, 'utf8'), state);
  }
  return state;
}

function prismaDdl(): string {
  const cli = createRequire(join(API_ROOT, 'package.json')).resolve('prisma/build/index.js');
  const args = [cli, 'migrate', 'diff', '--from-empty', '--to-schema', 'prisma/schema', '--script'];
  const result = spawnSync(process.execPath, args, {
    cwd: API_ROOT,
    encoding: 'utf8',
    // The schema engine needs a datasource URL even for an offline diff; it does not connect.
    env: {
      ...process.env,
      MIGRATION_DATABASE_URL:
        process.env['MIGRATION_DATABASE_URL'] ?? 'postgresql://offline@localhost:5432/offline',
      PRISMA_HIDE_UPDATE_MESSAGE: '1',
    },
  });
  if (result.status !== 0) throw new Error(`prisma migrate diff failed:\n${result.stderr}`);
  return result.stdout.replace(/\r\n/g, '\n');
}

function buildInit(): void {
  const target = join(MIGRATIONS_DIR, INIT_MIGRATION, 'migration.sql');
  const set = readSchemaDir(SCHEMA_DIR);
  const sql = [
    '-- Kaam Karo schema v1 (T2.3; DATA-001; BP §25, §26, §66; D-001).',
    '-- GENERATED by prisma/tools/db-schema.ts init from prisma/schema and prisma/sql. Do not edit by hand.',
    '',
    readFileSync(join(SQL_DIR, '00_extensions.sql'), 'utf8'),
    '-- kk:section prisma-ddl (prisma migrate diff --from-empty --to-schema prisma/schema)',
    prismaDdl(),
    ...SQL_AFTER_DDL.map((file) => readFileSync(join(SQL_DIR, file), 'utf8')),
    '-- kk:section comments (generated from the /// docs; T2.3 acceptance "every table/column has a comment citing BP §")',
    renderCommentSql(buildCommentStatements(set)),
  ].join('\n');
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, sql.replace(/\r\n/g, '\n'));
  const lock = join(MIGRATIONS_DIR, 'migration_lock.toml');
  if (!existsSync(lock)) {
    writeFileSync(
      lock,
      '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
    );
  }
  console.log(`wrote ${target}`);
}

function printMissingComments(): void {
  const current = commentsInMigrations();
  const wanted = buildCommentStatements(readSchemaDir(SCHEMA_DIR));
  const missing = wanted.filter((s) => current.get(s.key) !== s.text);
  if (missing.length === 0) console.log('-- comments are up to date');
  else console.log(renderCommentSql(missing));
}

const command = process.argv[2];
if (command === 'init') buildInit();
else if (command === 'comments') printMissingComments();
else if (command !== undefined) {
  console.error('usage: node prisma/tools/db-schema.ts init|comments');
  process.exit(2);
}
