/**
 * Request ID + security headers for every request (T2.2).
 * - REL-001 / INFRA-005 (BP §31.1, §34): each request gets a request ID (`X-Request-Id`), echoed in
 *   the response, in every log line and in the error envelope, so support can trace a failure.
 *   A client-sent ID is accepted only if it is a safe short token; otherwise a new UUID is used.
 * - SEC-REVIEW-T2.1 #10 (BP §29): no `X-Powered-By`; JSON-API security headers; HSTS in
 *   deployed environments (SEC-BASE-001 encrypted traffic). No new library (D-001 check).
 */
import { randomUUID } from 'node:crypto';
import { Inject, Injectable, type NestMiddleware } from '@nestjs/common';
import type {
  NextFn as NextFunction,
  HttpRequest as Request,
  HttpResponse as Response,
} from './http-types';
import { type ServerEnv, isDeployedEnv, runWithRequestContext } from '@kaamkaro/platform';
import { SERVER_ENV } from '../config/server-env.module';

export const REQUEST_ID_HEADER = 'x-request-id';
/** A client trace ID is kept only as a hint (`clientRequestId`), never as the request ID. */
const SAFE_REQUEST_ID = /^[A-Za-z0-9_-]{8,64}$/;
/** HSTS max-age: one year (technical standard value for HTTPS-only APIs). */
const HSTS_MAX_AGE_SECONDS = 31_536_000;

export function requestIdOf(req: Request): string | null {
  return typeof req.requestId === 'string' ? req.requestId : null;
}

/** The client's own trace ID (validated, bounded), for logs and support only. */
export function clientRequestIdOf(req: Request): string | null {
  return typeof req.clientRequestId === 'string' ? req.clientRequestId : null;
}

/**
 * Request ID + security headers on one response. Used by the middleware and, for responses that
 * never reach it (body-parser 400/413), by the error filter (SEC-REVIEW-T2.2 #11).
 */
export function applyRequestContext(req: Request, res: Response, env: ServerEnv): string {
  if (!req.requestId) {
    // SEC-REVIEW-T2.2 #12: the request ID is ALWAYS generated by the server.
    req.requestId = randomUUID();
    const incoming = req.headers[REQUEST_ID_HEADER];
    if (typeof incoming === 'string' && SAFE_REQUEST_ID.test(incoming)) {
      req.clientRequestId = incoming;
    }
  }
  if (res.headersSent) return req.requestId;
  res.removeHeader('X-Powered-By');
  res.setHeader('X-Request-Id', req.requestId);
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.setHeader('X-Frame-Options', 'DENY');
  res.setHeader('Referrer-Policy', 'no-referrer');
  res.setHeader('Content-Security-Policy', "default-src 'none'; frame-ancestors 'none'");
  res.setHeader('Cross-Origin-Resource-Policy', 'same-origin');
  res.setHeader('Cache-Control', 'no-store');
  if (isDeployedEnv(env.appEnv)) {
    res.setHeader(
      'Strict-Transport-Security',
      `max-age=${HSTS_MAX_AGE_SECONDS}; includeSubDomains`,
    );
  }
  return req.requestId;
}

@Injectable()
export class RequestContextMiddleware implements NestMiddleware {
  constructor(@Inject(SERVER_ENV) private readonly env: ServerEnv) {}

  use(req: Request, res: Response, next: NextFunction): void {
    const requestId = applyRequestContext(req, res, this.env);
    const clientRequestId = clientRequestIdOf(req);
    runWithRequestContext({ requestId, clientRequestId }, () => next());
  }
}
